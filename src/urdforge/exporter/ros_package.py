"""URDForge ROS / ROS 2 Robot Package Exporter.

Generates complete, production-grade ROS 2 (and ROS 1) description packages
including package.xml, CMakeLists.txt, URDF, meshes, and launch/rviz configurations.
"""

from __future__ import annotations

import os
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

from urdforge.core.robot_model import RobotModel


@dataclass
class ROSPackageConfig:
    """Configuration for exporting a ROS package."""

    package_name: str
    robot_name: str
    version: str = "0.1.0"
    description: str = "Simulation-ready URDF description package generated by URDForge"
    author_name: str = "URDForge Developer"
    author_email: str = "developer@urdforge.ai"
    license_type: str = "Apache-2.0"
    generate_ros2_launch: bool = True
    generate_ros1_launch: bool = True
    use_package_uri: bool = True


class ROSPackageExporter:
    """Exports a robot model into a standardized ROS/ROS 2 description package."""

    def __init__(self, robot: RobotModel, config: ROSPackageConfig) -> None:
        self.robot = robot
        self.config = config

    def export(
        self,
        target_directory: Path | str,
        exported_mesh_paths: Optional[Dict[str, Path]] = None,
    ) -> Path:
        """Export the full ROS package to target_directory.

        Args:
            target_directory: Directory where the package folder will be created.
            exported_mesh_paths: Dict mapping part_name -> local STL mesh Path on disk.
        """
        base_dir = Path(target_directory).resolve()
        pkg_dir = base_dir / self.config.package_name
        pkg_dir.mkdir(parents=True, exist_ok=True)

        urdf_dir = pkg_dir / "urdf"
        meshes_vis_dir = pkg_dir / "meshes" / "visual"
        meshes_col_dir = pkg_dir / "meshes" / "collision"
        launch_dir = pkg_dir / "launch"
        rviz_dir = pkg_dir / "rviz"

        for d in (urdf_dir, meshes_vis_dir, meshes_col_dir, launch_dir, rviz_dir):
            d.mkdir(parents=True, exist_ok=True)

        # 1. Copy or place mesh files
        if exported_mesh_paths:
            for part_name, src_mesh in exported_mesh_paths.items():
                if src_mesh.exists():
                    dst_vis = meshes_vis_dir / f"{part_name}.stl"
                    dst_col = meshes_col_dir / f"{part_name}.stl"
                    shutil.copy2(src_mesh, dst_vis)
                    shutil.copy2(src_mesh, dst_col)

        # 2. Update mesh references in URDF to "package://<pkg_name>/meshes/..."
        urdf_text = self._generate_urdf_with_package_uri()
        urdf_file = urdf_dir / f"{self.config.robot_name}.urdf"
        with open(urdf_file, "w", encoding="utf-8") as f:
            f.write(urdf_text)

        # 3. Generate package.xml (Format 3)
        pkg_xml_file = pkg_dir / "package.xml"
        with open(pkg_xml_file, "w", encoding="utf-8") as f:
            f.write(self._generate_package_xml())

        # 4. Generate CMakeLists.txt (Compatible with ament_cmake / colcon)
        cmake_file = pkg_dir / "CMakeLists.txt"
        with open(cmake_file, "w", encoding="utf-8") as f:
            f.write(self._generate_cmakelists())

        # 5. Generate ROS 2 launch file
        if self.config.generate_ros2_launch:
            l2_file = launch_dir / "display.launch.py"
            with open(l2_file, "w", encoding="utf-8") as f:
                f.write(self._generate_ros2_launch())

        # 6. Generate ROS 1 launch file
        if self.config.generate_ros1_launch:
            l1_file = launch_dir / "display.launch"
            with open(l1_file, "w", encoding="utf-8") as f:
                f.write(self._generate_ros1_launch())

        # 7. Generate default RViz config
        rviz_file = rviz_dir / "urdf.rviz"
        with open(rviz_file, "w", encoding="utf-8") as f:
            f.write(self._generate_rviz_config())

        return pkg_dir

    def _generate_urdf_with_package_uri(self) -> str:
        """Produce URDF text where meshes use package:// URI or complete relative paths."""
        pkg_name = self.config.package_name if self.config.use_package_uri else None
        return self.robot.to_urdf_xml(package_name=pkg_name)

    def _generate_package_xml(self) -> str:
        c = self.config
        return f"""<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>{c.package_name}</name>
  <version>{c.version}</version>
  <description>{c.description}</description>
  <maintainer email="{c.author_email}">{c.author_name}</maintainer>
  <license>{c.license_type}</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <exec_depend>xacro</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""

    def _generate_cmakelists(self) -> str:
        c = self.config
        return f"""cmake_minimum_required(VERSION 3.8)
project({c.package_name})

if(CMAKE_COMPILER_IS_GNUCXX OR CMAKE_CXX_COMPILER_ID MATCHES "Clang")
  add_compile_options(-Wall -Wextra -Wpedantic)
endif()

find_package(ament_cmake REQUIRED)

install(DIRECTORY
  launch
  rviz
  urdf
  meshes
  DESTINATION share/${{PROJECT_NAME}}
)

ament_package()
"""

    def _generate_ros2_launch(self) -> str:
        c = self.config
        return f"""import os
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node

def generate_launch_description():
    pkg_share = get_package_share_directory('{c.package_name}')
    default_urdf_path = os.path.join(pkg_share, 'urdf', '{c.robot_name}.urdf')
    default_rviz_config_path = os.path.join(pkg_share, 'rviz', 'urdf.rviz')

    with open(default_urdf_path, 'r') as infp:
        robot_desc = infp.read()

    return LaunchDescription([
        DeclareLaunchArgument(
            name='model',
            default_value=default_urdf_path,
            description='Absolute path to robot urdf file'
        ),
        Node(
            package='robot_state_publisher',
            executable='robot_state_publisher',
            name='robot_state_publisher',
            output='screen',
            parameters=[{{'robot_description': robot_desc}}]
        ),
        Node(
            package='joint_state_publisher_gui',
            executable='joint_state_publisher_gui',
            name='joint_state_publisher_gui',
            output='screen'
        ),
        Node(
            package='rviz2',
            executable='rviz2',
            name='rviz2',
            output='screen',
            arguments=['-d', default_rviz_config_path]
        )
    ])
"""

    def _generate_ros1_launch(self) -> str:
        c = self.config
        return f"""<launch>
  <arg name="model" default="$(find {c.package_name})/urdf/{c.robot_name}.urdf"/>
  <arg name="gui" default="true"/>
  <arg name="rvizconfig" default="$(find {c.package_name})/rviz/urdf.rviz"/>

  <param name="robot_description" textfile="$(arg model)"/>

  <node if="$(arg gui)" name="joint_state_publisher" pkg="joint_state_publisher_gui" type="joint_state_publisher_gui"/>
  <node unless="$(arg gui)" name="joint_state_publisher" pkg="joint_state_publisher" type="joint_state_publisher"/>
  <node name="robot_state_publisher" pkg="robot_state_publisher" type="robot_state_publisher"/>
  <node name="rviz" pkg="rviz" type="rviz" args="-d $(arg rvizconfig)" required="true"/>
</launch>
"""

